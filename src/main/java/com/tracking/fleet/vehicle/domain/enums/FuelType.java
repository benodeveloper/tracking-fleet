package com.tracking.fleet.vehicle.domain.enums;

/**
 * Fuel types supported by fleet vehicles.
 */
public enum FuelType {

  /** Petrol (gasoline) engine. */
  PETROL,

  /** Diesel engine. */
  DIESEL,

  /** Battery electric vehicle. */
  ELECTRIC,

  /** Combined combustion and electric powertrain. */
  HYBRID,

  /** Liquefied petroleum gas. */
  LPG,

  /** Compressed natural gas. */
  CNG
}
