package com.tracking.fleet.vehicle.domain.enums;

/**
 * Categories of vehicles managed by the fleet.
 */
public enum VehicleType {

  /** Heavy-duty goods vehicle. */
  TRUCK,

  /** Light goods or passenger van. */
  VAN,

  /** Passenger car. */
  CAR,

  /** Motorcycle. */
  MOTORCYCLE,

  /** Passenger bus. */
  BUS,

  /** Unpowered cargo trailer. */
  TRAILER
}
